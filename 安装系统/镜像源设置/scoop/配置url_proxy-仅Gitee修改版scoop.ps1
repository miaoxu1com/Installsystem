# 功能: 配置自建 url_proxy
# 注意: 只有 Gitee 修改版 scoop(https://gitee.com/scoop-installer-mirrors)才支持 url_proxy，
#       archive 分支和原版 scoop 设置无效
# 可供设置的代理站:
#   https://pd.zwc365.com (文件大小限制 2G)
#   https://pd.zwc365.com/cfworker (CloudFlare 加速，文件大小无限制)

# 添加代理
scoop config URL_PROXY "https://scoop.201704.xyz"

# 删除代理
# scoop config rm URL_PROXY
